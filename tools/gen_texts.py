#!/usr/bin/env python3
"""Turns ada/data/texts.tsv into ada/src/uim-texts.ads (plain Ada data).

Every row is   english <TAB> german <TAB> spanish <TAB> french.
All texts go into one byte string (Pool). Row K of each language is the
slice Pool (Start (K, L) .. Start (K, L) + Size (K, L) - 1).
Rows are sorted by their first English byte, longest first, so the matcher
only has to look at one bucket and can stop at the first hit.
The output is deterministic: same TSV in, same Ada file out.
"""
import sys
src, dst = sys.argv[1], sys.argv[2]
rows, seen = [], set()
for n, line in enumerate(open(src, encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line or (line.startswith('#') and '\t' not in line):
        continue                                    # empty line or comment
    cols = line.split('\t')
    if len(cols) != 4:
        sys.exit(f'{src}:{n}: need 4 columns, got {len(cols)}')
    cols = [' '.join(c.split()) for c in cols]      # one space between words
    if cols[0] in seen:
        continue                                    # first row wins
    seen.add(cols[0])
    rows.append([c.encode('utf-8') for c in cols])
rows.sort(key=lambda r: (r[0][0], -len(r[0]), r[0]))
pool, start, size = bytearray(), [], []
for r in rows:
    s = []
    for c in r:
        s.append(len(pool) + 1); pool += c
    start.append(s); size.append([len(c) for c in r])
first = {}
for k, r in enumerate(rows, 1):
    b = r[0][0]
    lo, hi = first.get(b, (k, k)); first[b] = (min(lo, k), k)

def lit(chunk):
    """Ada text for some bytes: plain ASCII in quotes, other bytes as Character'Val."""
    out, cur = [], ''
    for b in chunk:
        if 32 <= b < 127:
            cur += '""' if b == 34 else chr(b)
        else:
            if cur: out.append('"' + cur + '"'); cur = ''
            out.append(f"Character'Val ({b})")
    if cur: out.append('"' + cur + '"')
    return ' & '.join(out) if out else '""'

o = []
o.append('--  Generated by tools/gen_texts.py from ada/data/texts.tsv. Do not edit.')
o.append('package UIM.Texts is')
o.append(f'   Count : constant := {len(rows)};')
o.append(f'   Pool_Size : constant := {len(pool)};')
o.append('   Pool : constant String (1 .. Pool_Size) :=')
parts = [bytes(pool[i:i+60]) for i in range(0, len(pool), 60)]
# bytes >= 128 are written as Character'Val so the source stays ASCII
o.append('     ' + '\n     & '.join(lit(p) for p in parts) + ';')
for name, arr in (('Start', start), ('Size', size)):
    o.append(f'   {name} : constant array (1 .. Count, Language) of Natural := (')
    o.append(',\n'.join(f'      ({a[0]}, {a[1]}, {a[2]}, {a[3]})' for a in arr) + ');')
o.append('   --  Rows whose English text starts with byte B are First (B) .. Last (B).')
o.append('   First : constant array (Character) of Natural := (')
o.append(''.join(f'      Character\'Val ({b}) => {first[b][0]},\n' for b in sorted(first)) + '      others => 1);')
o.append('   Last : constant array (Character) of Natural := (')
o.append(''.join(f'      Character\'Val ({b}) => {first[b][1]},\n' for b in sorted(first)) + '      others => 0);')
o.append('end UIM.Texts;')
open(dst, 'w').write('\n'.join(o) + '\n')
print(f'{len(rows)} rows, {len(pool)} bytes of text')
